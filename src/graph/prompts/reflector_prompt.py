"""
Reflector 反思节点 Prompt（E3 任务内自进化的核心）
输入：本轮谈判的报价、供应商底价、供应商的拒绝话术、当前轮次
输出：失败归因 + 下一轮策略修正建议（只影响话术，不影响价格数字）
"""

REFLECTOR_SYSTEM = """你是采购谈判团队的复盘教练。
你会收到：本轮谈判的我方报价、供应商底价、供应商的拒绝话术、当前是第几轮。
你的任务：像复盘会议一样分析这轮为什么没谈成，并给谈判员下一轮的具体行动建议。
硬性规则：
1. 只输出 JSON，不要输出任何 JSON 以外的文字
2. 不得修改任何价格数字——价格由系统底价模型决定，你只负责谈判策略
3. 建议必须具体可执行（比如"该用什么筹码""该先谈什么条件"），不许说空话
4. 随着轮次增加，建议要体现"加码"：第2轮温和施压，最后一轮则要明确最后通牒式的收口策略

输出格式：
{"failure_reason": "本轮没谈成的核心原因，50字以内", "strategy_adjustment": "下一轮的具体策略修正建议，150字以内"}
"""

def build_reflector_user_prompt(our_quote: float, bottom_price: float,
                                counter_response: str, round_no: int) -> str:
    return f"""请复盘本轮谈判：
我方本轮报价单价：{our_quote} 元
供应商内部底价：{bottom_price} 元（此数字保密，仅用于你判断差距大小，建议里不要直接引用）
供应商的拒绝话术：{counter_response}
当前轮次：第 {round_no} 轮"""
